"""Narration for the hadi.ai reel: deep, calm, confident male voice (local Kokoro TTS).

Generates every line separately, lays them out with deliberate pauses, and writes:
  $OUT/voice_raw.wav  - the narration track (24 kHz)
  timeline.js         - when each line starts/ends, which reel.html uses to time every scene and kill
Usage: python3 voice.py <kokoro-dir> <out-dir>
"""
import json
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

KDIR, OUT = sys.argv[1], sys.argv[2]
SPEED = 1.0

# (id, text, pause after in seconds). The pauses give the visuals room to build before each kill.
LINES = [
    ('h1', 'You spent four years learning it.', .35),
    ('h2', 'A.I. learned it… in four seconds.', .5),
    ('c1', 'Coding.', .3),
    ('c2', 'A full login page. Written in seconds.', .8),
    ('c3', 'Coding is dead.', .6),
    ('d1', 'Design.', .3),
    ('d2', 'A launch poster, ready before your coffee.', .8),
    ('d3', 'Design is dead.', .6),
    ('a1', 'Accounting.', .3),
    ('a2', 'The whole quarter, closed in seconds.', .8),
    ('a3', 'Accounting is dead.', .7),
    ('r0', 'And it does not stop there.', .15),
    ('r1', 'Translation.', .04),
    ('r2', 'Copywriting.', .04),
    ('r3', 'Data analysis.', .04),
    ('r4', 'Legal research.', .04),
    ('r5', 'Market research.', .04),
    ('r6', 'Customer support.', .35),
    ('r7', 'Years of study… automated.', .6),
    ('m1', 'So adapt fast.', .3),
    ('m2', 'Or get replaced.', .55),
    ('m3', 'Learn the A.I. tools. Multiply your output.', .7),
    ('e1', 'Haadi dot A.I.', .5),
    ('e2', 'Follow for more.', 1.4),
]
LEAD_IN = .35

k = Kokoro(f'{KDIR}/kokoro-v1.0.onnx', f'{KDIR}/voices-v1.0.bin')
# mostly the deepest voice (onyx), with some of michael's clarity
style = .7 * k.get_voice_style('am_onyx') + .3 * k.get_voice_style('am_michael')


def trim(a, sr, thr=.025):
    idx = np.nonzero(np.abs(a) > thr)[0]
    if not len(idx): return a
    s, e = max(0, idx[0] - int(.02 * sr)), min(len(a), idx[-1] + int(.06 * sr))
    return a[s:e]


track, marks, sr = [], {}, 24000
t = LEAD_IN
track.append(np.zeros(int(LEAD_IN * sr)))
for lid, text, pause in LINES:
    a, sr = k.create(text, voice=style, speed=SPEED, lang='en-us')
    a = trim(a, sr)
    d = len(a) / sr
    marks[lid] = [round(t, 3), round(t + d, 3)]
    track += [a, np.zeros(int(pause * sr))]
    t += d + pause

audio = np.concatenate(track).astype(np.float32)
sf.write(f'{OUT}/voice_raw.wav', audio, sr)
with open('timeline.js', 'w') as f:
    f.write('// generated by voice.py: start/end (s) of every narration line\n')
    f.write(f'window.VO = {json.dumps(marks)};\nwindow.VO_DUR = {round(t, 3)};\n')
print(f'narration {t:.2f}s')
for lid, (a, b) in marks.items(): print(f'{lid:3s} {a:6.2f} {b:6.2f}')
